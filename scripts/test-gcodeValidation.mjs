import assert from 'node:assert/strict'
import fs from 'node:fs'
import vm from 'node:vm'
import esbuild from 'esbuild'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)

const source = fs.readFileSync('src/main/services/engines/gcodeValidationEngine.ts', 'utf8')
const compiled = esbuild.transformSync(source, { loader: 'ts', format: 'cjs', target: 'node18' }).code
const module = { exports: {} }
vm.runInNewContext(compiled, { module, exports: module.exports, require })
const { GcodeValidationEngine } = module.exports

const officialStyle = '; generated by ElegooSlicer\n; total layer number: 42\nM104 S220\nM140 S60\nG1 X10 Y10 E0.5\n'
const validResult = GcodeValidationEngine.validateForPrint(officialStyle)
assert.equal(validResult.valid, true)
assert.equal(validResult.layerCount, 42)

const prototype = '; Generated by kuziSlicer\nM104 S200\nM140 S60\nG0 X1 Y1\nG0 E10\n'
const result = GcodeValidationEngine.validateForPrint(prototype)
assert.equal(result.valid, false)
assert.ok(result.errors.some((error) => error.includes('Prototype')))
assert.ok(result.errors.some((error) => error.includes('extrusion')))

const dangerous = `${officialStyle}BED_MESH_CALIBRATE\n`
assert.equal(GcodeValidationEngine.validateForPrint(dangerous).valid, false)

console.log('PASS: print safety validation accepts sliced output and blocks prototype/dangerous G-code')
