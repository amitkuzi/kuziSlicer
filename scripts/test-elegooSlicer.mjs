import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import esbuild from 'esbuild'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const built = esbuild.buildSync({ entryPoints: [path.resolve('src/main/services/elegooSlicerService.ts')], bundle: true, platform: 'node', format: 'cjs', write: false })
const mod = { exports: {} }
new Function('module', 'exports', 'require', built.outputFiles[0].text)(mod, mod.exports, require)
const { ElegooSlicerService } = mod.exports

const work = fs.mkdtempSync(path.join(os.tmpdir(), 'kuzislicer-elegoo-'))
const model = path.join(work, 'cube.stl')
const vertices = [[0,0,0],[20,0,0],[20,20,0],[0,20,0],[0,0,20],[20,0,20],[20,20,20],[0,20,20]]
const faces = [[0,2,1],[0,3,2],[4,5,6],[4,6,7],[0,1,5],[0,5,4],[1,2,6],[1,6,5],[2,3,7],[2,7,6],[3,0,4],[3,4,7]]
const facets = faces.map((face) => `facet normal 0 0 0\nouter loop\n${face.map((i) => `vertex ${vertices[i].join(' ')}`).join('\n')}\nendloop\nendfacet`).join('\n')
fs.writeFileSync(model, `solid cube\n${facets}\nendsolid cube\n`)

try {
  const output = await ElegooSlicerService.slice({ modelPath: model, outputDirectory: work, nozzleSize: 0.4, filamentMaterial: 'PLA' })
  const gcode = fs.readFileSync(output, 'utf8')
  assert.match(gcode, /generated by ElegooSlicer/i)
  assert.match(gcode, /^G1\b[^\r\n]*\bE-?\d/m)
  assert.doesNotMatch(gcode, /Generated by kuziSlicer/i)
  console.log(`PASS: official ElegooSlicer produced printable Centauri Carbon G-code (${fs.statSync(output).size} bytes)`)
} finally {
  fs.rmSync(work, { recursive: true, force: true })
}
