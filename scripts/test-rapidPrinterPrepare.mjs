import assert from 'node:assert/strict'
import path from 'node:path'
import fs from 'node:fs'
import { createHash } from 'node:crypto'
import { createRequire } from 'node:module'
import { zipSync, strToU8 } from 'fflate'
import esbuild from 'esbuild'

const require = createRequire(import.meta.url)
const built = esbuild.buildSync({ entryPoints: [path.resolve('src/printer-extensions/bambulab-a1-mini/prepare.ts')],
  bundle: true, platform: 'node', format: 'cjs', write: false })
const mod = { exports: {} }
new Function('module', 'exports', 'require', built.outputFiles[0].text)(mod, mod.exports, require)
const { prepare } = mod.exports
const gcode = '; BambuStudio\n; total layer number: 1\n; max_z_height: 1\nM104 S220\nM140 S60\nG1 X10 Y10 Z1 E1\n'
const settings = { printer_model: 'Bambu Lab A1 mini', nozzle_diameter: ['0.4'] }
function archive(options = {}) {
  const code = options.gcode ?? gcode
  const plate = 'Metadata/plate_3.gcode'
  const entries = {
    [plate]: strToU8(code), [`${plate}.md5`]: strToU8(createHash('md5').update(code).digest('hex')),
    'Metadata/project_settings.config': strToU8(JSON.stringify(options.settings ?? settings)),
    'Metadata/slice_info.config': strToU8(options.slice ?? '<config><plate><metadata key="index" value="3"/><metadata key="printer_model_id" value="N1"/><metadata key="nozzle_diameters" value="0.4"/></plate></config>'),
    ...options.entries,
  }
  for (const key of options.omit ?? []) delete entries[key]
  return zipSync(entries)
}
let passed = 0
function test(name, action) { action(); passed++; console.log(`PASS: ${name}`) }
test('Prepare_ValidPlate3_PreservesOriginalBytesAndDigest', () => {
  const input = archive(), job = prepare(input, 0.4)
  assert.equal(job.plate, 'Metadata/plate_3.gcode')
  assert.deepEqual(job.bytes, input)
  assert.equal(job.sha256, createHash('sha256').update(input).digest('hex'))
  input[0] = 0
  assert.notEqual(job.bytes[0], input[0])
})
test('Prepare_InvalidNozzle_Rejects', () => {
  for (const nozzle of [0, 0.8, NaN, Infinity]) assert.throws(() => prepare(archive(), nozzle), /Unsupported nozzle/)
})
test('Prepare_EmptyOrCorruptZip_Rejects', () => {
  for (const input of [new Uint8Array(), new Uint8Array([1, 2, 3])]) assert.throws(() => prepare(input, 0.4))
})
test('Prepare_MissingRequiredEntries_Rejects', () => {
  for (const entry of ['Metadata/plate_3.gcode', 'Metadata/plate_3.gcode.md5', 'Metadata/project_settings.config', 'Metadata/slice_info.config']) {
    assert.throws(() => prepare(archive({ omit: [entry] }), 0.4))
  }
})
test('Prepare_MultiplePlates_RejectsAmbiguousSelection', () => {
  assert.throws(() => prepare(archive({ entries: { 'Metadata/plate_1.gcode': strToU8(gcode) } }), 0.4), /exactly one/)
})
test('Prepare_ArchiveTraversal_Rejects', () => {
  for (const name of ['../escape', '/absolute', 'Metadata/../../escape', 'Metadata\\escape']) {
    assert.throws(() => prepare(archive({ entries: { [name]: strToU8('bad') } }), 0.4), /Unsafe archive/)
  }
})
test('Prepare_WrongMachineOrNozzle_Rejects', () => {
  for (const value of [{ ...settings, printer_model: 'Bambu Lab A1' }, { ...settings, nozzle_diameter: ['0.6'] }, { ...settings, nozzle_diameter: [] }]) {
    assert.throws(() => prepare(archive({ settings: value }), 0.4))
  }
})
test('Prepare_WrongPlateMetadata_Rejects', () => {
  assert.throws(() => prepare(archive({ slice: '<metadata key="index" value="1"/>' }), 0.4), /metadata mismatch/)
})
test('Prepare_CorruptChecksum_Rejects', () => {
  assert.throws(() => prepare(archive({ entries: { 'Metadata/plate_3.gcode.md5': strToU8('bad') } }), 0.4), /checksum mismatch/)
})
test('Prepare_UnverifiedOrPrototypeGcode_Rejects', () => {
  for (const code of ['', gcode.replace('; BambuStudio', '; unknown generator'), gcode + '; Generated by kuziSlicer']) {
    assert.throws(() => prepare(archive({ gcode: code }), 0.4))
  }
})
test('Prepare_ExcessiveTemperatureOrHeight_Rejects', () => {
  for (const code of [gcode + 'M109 S301\n', gcode + 'M190 S81\n', gcode + 'M104 S-1\n', gcode.replace('max_z_height: 1', 'max_z_height: 181')]) {
    assert.throws(() => prepare(archive({ gcode: code }), 0.4))
  }
})
test('Prepare_DangerousCommands_Rejects', () => {
  for (const command of ['M112', 'M502', 'M997', 'M999']) {
    assert.throws(() => prepare(archive({ gcode: gcode + command + '\n' }), 0.4), /configuration command/)
  }
})
test('Prepare_NativeCalibrationSave_AllowsBambuM500', () => {
  assert.doesNotThrow(() => prepare(archive({ gcode: gcode + '  M500 ; save cali data\n' }), 0.4))
})
const attachment = process.argv[2]
if (attachment) test('Prepare_UserAttachment_A1MiniPoint4Plate3', () => {
  const job = prepare(fs.readFileSync(attachment), 0.4)
  assert.equal(job.plate, 'Metadata/plate_3.gcode')
  assert.equal(job.model, 'Bambu Lab A1 mini')
  assert.throws(() => prepare(fs.readFileSync(attachment), 0.2), /nozzle mismatch/)
  assert.throws(() => prepare(fs.readFileSync(attachment), 0.6), /nozzle mismatch/)
})
console.log(`PASS: ${passed} independent archive validation cases`)
