// Round-trip + adversarial self-check for the A1 mini packaging path:
// kuziSlicer G-code -> buildProject() -> prepare() must accept it, and every
// tampered / malformed variant must be rejected.
// Run: node scripts/test-bambuProject.mjs [model.stl]
import assert from 'node:assert/strict'
import path from 'node:path'
import fs from 'node:fs'
import crypto from 'node:crypto'
import esbuild from 'esbuild'
import { createRequire } from 'node:module'
import { unzipSync, zipSync, strFromU8, strToU8 } from 'fflate'

const require = createRequire(import.meta.url)
const load = (entry) => {
  const out = esbuild.buildSync({ entryPoints: [path.resolve(entry)], bundle: true, platform: 'node', format: 'cjs', write: false })
  const mod = { exports: {} }
  new Function('module', 'exports', 'require', out.outputFiles[0].text)(mod, mod.exports, require)
  return mod.exports
}

const { sliceLocally, parseModelGeometry } = load('src/main/services/localSlicer.ts')
const { buildProject } = load('src/printer-extensions/bambulab-a1-mini/package.ts')
const { prepare } = load('src/printer-extensions/bambulab-a1-mini/prepare.ts')
const { profiles } = load('src/printer-extensions/bambulab-a1-mini/profiles.ts')

const model = process.argv[2] || 'D:/Downloads/FlaxCat.stl'
const printer = profiles.find((p) => p.nozzleSize === 0.4)
const filament = require('../src/data/filaments.json').filaments.find((f) => f.id === 'pla-generic')
const settings = { layerHeight: 0.2, infillDensity: 15, infillPattern: 'grid', shellThickness: 0.8, supportEnabled: false, fanSpeed: 100 }

const geometry = parseModelGeometry(model)
const gcode = sliceLocally({ modelPath: model, printerProfile: printer, filamentProfile: filament, settings })

// buildProject measures the footprint from the toolpaths; the model's own size is the
// independent yardstick the packaged file has to agree with.
const size = geometry.bounds.max.map((v, i) => v - geometry.bounds.min[i])
const bounds = {
  minX: printer.bedSizeX / 2 - size[0] / 2, maxX: printer.bedSizeX / 2 + size[0] / 2,
  minY: printer.bedSizeY / 2 - size[1] / 2, maxY: printer.bedSizeY / 2 + size[1] / 2,
  maxZ: size[2],
}
const options = { nozzleTemp: filament.extruderTemp, bedTemp: filament.bedTemp, nozzle: 0.4, objectName: path.basename(model) }

const project = buildProject(gcode, options)
const prepared = prepare(new Uint8Array(project), 0.4)
assert.equal(prepared.plate, 'Metadata/plate_1.gcode')
assert.equal(prepared.model, 'Bambu Lab A1 mini')

const plate = strFromU8(unzipSync(new Uint8Array(project))['Metadata/plate_1.gcode'])
const lines = plate.split('\n')

// --- the packaged plate must be a real A1 mini job, not our raw prototype output ---
assert.ok(!/Generated by kuziSlicer/i.test(plate), 'raw prototype header must not survive packaging')
assert.ok(plate.includes('; MACHINE_START_GCODE_END'), 'machine start block must be present')
assert.ok(plate.includes('; MACHINE_END_GCODE_START'), 'machine end block must be present')
assert.ok(plate.trimEnd().endsWith('; EXECUTABLE_BLOCK_END'), 'plate must end with the executable block')
// The CONFIG_BLOCK legitimately quotes the unexpanded presets; the executable part must not.
const executable = plate.slice(plate.indexOf('; EXECUTABLE_BLOCK_START'))
assert.ok(!/[{[](?:if |first_layer|nozzle_temperature|max_layer_z)/.test(executable), 'no unexpanded template placeholders may remain')
// Levelling must cover the object's real footprint (half a line width inside the mesh outline).
const level = lines.find((l) => l.trim().startsWith('G29 A1 X')).match(/X([\d.-]+) Y([\d.-]+) I([\d.-]+) J([\d.-]+)/)
assert.ok(Math.abs(Number(level[1]) - bounds.minX) < 0.5 && Math.abs(Number(level[2]) - bounds.minY) < 0.5,
  `bed levelling origin ${level[1]},${level[2]} must match the object footprint ${bounds.minX},${bounds.minY}`)
assert.ok(Math.abs(Number(level[3]) - size[0]) < 1 && Math.abs(Number(level[4]) - size[1]) < 1,
  'bed levelling area must match the object size')
assert.ok(lines.some((l) => l.trim() === `M104 S${filament.extruderTemp}`), 'nozzle temp must be retargeted to the chosen filament')
assert.ok(lines.some((l) => l.trim().startsWith(`M190 S${filament.bedTemp}`)), 'bed temp must be retargeted to the chosen filament')

// --- geometry safety: everything inside the build volume, first layer not scraping ---
const layerCount = Number(plate.match(/^; total layer number: (\d+)$/m)[1])
assert.ok(layerCount > 1, 'layer count must be recorded')
assert.equal(lines.filter((l) => /^; layer num\/total_layer_count: \d+\/\d+$/.test(l)).length, layerCount,
  'every layer must emit a firmware progress marker')
// Bambu Studio's Preview tab segments "prepare" from "printing" at ; CHANGE_LAYER and
// times each layer from ; Z_HEIGHT / ; LAYER_HEIGHT -- without them it timed a whole
// packaged file as 100% prepare (2+ days) and showed an empty plate, model time 0s.
assert.equal(lines.filter((l) => l === '; CHANGE_LAYER').length, layerCount, 'every layer must mark ; CHANGE_LAYER')
assert.equal(lines.filter((l) => /^; Z_HEIGHT: [\d.]+$/.test(l)).length, layerCount, 'every layer must report ; Z_HEIGHT')
assert.ok(lines.every((l, i) => l !== '; CHANGE_LAYER' || lines[i + 1] === `; Z_HEIGHT: ${lines[i + 1]?.match(/[\d.]+/)?.[0]}`),
  '; CHANGE_LAYER must be immediately followed by ; Z_HEIGHT')
assert.ok(lines.some((l) => l === `; LAYER_HEIGHT: ${settings.layerHeight}`), 'layer height must be reported to Bambu Studio')
// Bambu/Orca colours the Preview by ; FEATURE:, not kuziSlicer's own ;TYPE: convention.
for (const feature of ['Outer wall', 'Inner wall', 'Sparse infill']) {
  assert.ok(lines.some((l) => l === `; FEATURE: ${feature}`), `expected a ; FEATURE: ${feature} tag`)
}

let first = null, maxZ = 0
for (const line of lines.slice(lines.indexOf('; layer num/total_layer_count: 1/' + layerCount))) {
  const z = line.match(/^G1 Z([\d.]+) F600$/)
  if (!z) continue
  if (first === null) first = Number(z[1])
  maxZ = Math.max(maxZ, Number(z[1]))
}
assert.equal(first, settings.layerHeight, `first layer must sit at one layer height, got ${first}`)
assert.ok(maxZ <= printer.bedSizeZ, 'no layer may exceed the build height')

let bad = 0
for (const line of lines) {
  const m = line.match(/^G[01] X(-?[\d.]+) Y(-?[\d.]+)(?: E|,| |$)/)
  if (!m) continue
  const [x, y] = [Number(m[1]), Number(m[2])]
  // Bambu's own macros deliberately move to negative X (the wipe/purge chute).
  if (x > printer.bedSizeX || y < -5 || y > printer.bedSizeY + 10) bad++
}
assert.equal(bad, 0, 'no move may leave the printable area')

// --- retraction must match the direct-drive extruder, not the filament's bowden default ---
const retracts = lines.filter((l) => /^G1 E-[\d.]+ F/.test(l))
assert.ok(retracts.length > 0, 'expected retractions')
for (const line of retracts.slice(0, 500)) {
  const mm = Number(line.match(/E-([\d.]+)/)[1])
  assert.ok(mm <= 1.5, `retraction ${mm}mm is a bowden value on a direct-drive extruder`)
}

// --- adversarial: prepare() must reject every tampered variant ---
const rejects = (label, mutate) => {
  const entries = unzipSync(new Uint8Array(project))
  mutate(entries)
  assert.throws(() => prepare(new Uint8Array(zipSync(entries, { level: 0 })), 0.4), undefined, `should reject: ${label}`)
}
rejects('tampered gcode without matching md5', (e) => { e['Metadata/plate_1.gcode'] = strToU8(strFromU8(e['Metadata/plate_1.gcode']) + '\nG1 X1 Y1\n') })
rejects('emergency stop injected', (e) => {
  const g = strFromU8(e['Metadata/plate_1.gcode']) + '\nM112\n'
  e['Metadata/plate_1.gcode'] = strToU8(g)
  e['Metadata/plate_1.gcode.md5'] = strToU8(crypto.createHash('md5').update(g, 'utf-8').digest('hex').toUpperCase())
})
rejects('nozzle temperature above the printer limit', (e) => {
  const g = strFromU8(e['Metadata/plate_1.gcode']).replace('M104 S200', 'M104 S420')
  e['Metadata/plate_1.gcode'] = strToU8(g)
  e['Metadata/plate_1.gcode.md5'] = strToU8(crypto.createHash('md5').update(g, 'utf-8').digest('hex').toUpperCase())
})
rejects('machine start sequence stripped', (e) => {
  const g = strFromU8(e['Metadata/plate_1.gcode']).replace('; MACHINE_START_GCODE_END', '; removed')
  e['Metadata/plate_1.gcode'] = strToU8(g)
  e['Metadata/plate_1.gcode.md5'] = strToU8(crypto.createHash('md5').update(g, 'utf-8').digest('hex').toUpperCase())
})
rejects('project re-targeted at another printer', (e) => {
  e['Metadata/project_settings.config'] = strToU8(
    strFromU8(e['Metadata/project_settings.config']).replace('"Bambu Lab A1 mini"', '"Bambu Lab X1 Carbon"'))
})
rejects('second plate smuggled in', (e) => { e['Metadata/plate_2.gcode'] = e['Metadata/plate_1.gcode'] })
assert.throws(() => prepare(new Uint8Array(project), 0.6), undefined, 'should reject a nozzle mismatch')
assert.throws(() => prepare(new Uint8Array(0), 0.4), undefined, 'should reject an empty project')

// --- adversarial: buildProject must refuse impossible inputs ---
const refuses = (label, gcodeIn, optionsIn) =>
  assert.throws(() => buildProject(gcodeIn, optionsIn), undefined, `should refuse: ${label}`)
refuses('unsupported nozzle', gcode, { ...options, nozzle: 0.6 })
refuses('bed temperature above the A1 mini limit', gcode, { ...options, bedTemp: 110 })
refuses('nozzle temperature above the A1 mini limit', gcode, { ...options, nozzleTemp: 400 })
// Bounds are measured from the toolpaths, so these have to be forced through the G-code.
const toy = (z, x) => `; Generated by kuziSlicer\n; Layer 1/1\nG1 Z${z} F600\nG1 X${x} Y10 E1 F3000\nG1 X${x + 5} Y20 E1 F3000\n`
refuses('object taller than the build volume', toy(200, 10), options)
refuses('toolpaths off the front of the bed', toy(10, 250), options)
refuses('no extrusion at all', '; Generated by kuziSlicer\n; Layer 1/1\nG1 Z1 F600\nG0 X10 Y10\n', options)
refuses('G-code with no layers', '; Generated by kuziSlicer\nG28\n', options)

const outPath = process.env.KUZI_PROJECT_OUT
if (outPath) fs.writeFileSync(outPath, project)

console.log(`PASS: ${path.basename(model)} -> ${layerCount} layers, ${(project.length / 1e6).toFixed(1)} MB project, ` +
  `first layer Z${first}, max Z${maxZ}, ${retracts.length} retractions; prepare() accepted it and rejected 8 tampered variants`)
